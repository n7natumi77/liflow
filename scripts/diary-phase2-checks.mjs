  await page.getByLabel("内容", { exact: true }).fill("試験用の支出"); await page.getByLabel("金額（円）", { exact: true }).fill("125"); await save();
  const temporaryMoney = (await snapshot()).find(e => e.payload.title === "試験用の支出");
