  await page.getByLabel("締切", { exact: true }).check();
  await page.locator('.week-grid-scroll').evaluate(node => { node.scrollTop = 10 * 56; });
  const target = page.locator('.week-day-column[data-date="2026-09-17"]');
  await target.scrollIntoViewIfNeeded();
