  assert.equal((await get("task3")).revision, task.revision + 1);
  assert.equal((await snapshot()).filter(e => e.type === "plan").length, planCount);
  await page.getByRole("button", { name: "帰りに買い物を未完了に戻す", exact: true }).click();
  await page.locator('[aria-label="タスクの表示"]').getByRole("button", { name: /^未完了/ }).click();
  await page.getByRole("textbox", { name: "タスクを検索", exact: true }).fill("資料を3本");
  assert.equal(await page.locator(".task-entry").count(), 1);
  await page.getByRole("textbox", { name: "タスクを検索", exact: true }).fill("");
  await screenshot("desktop-tasks");
  check("Task hierarchy, search and reversible completion preserve IDs and Plans");

  await menuTab("プロジェクト");
  await screenshot("desktop-projects");
  await page.locator('[data-project-id="project"]').getByRole("button", { name: "編集", exact: true }).click();
  assert.equal(await page.getByLabel("親プロジェクト", { exact: true }).locator('option[value="subproject"]').count(), 0);
  const project = await get("project");
