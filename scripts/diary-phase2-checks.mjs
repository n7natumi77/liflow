  assert.equal(await page.locator('.week-task-chip[data-task-id="task1"]').count(), 0);
  await screenshot("desktop-week");
  check("Week drops a linked Plan, keeps Task intact, clips overnight ranges, and leaves capacity unchanged by display filters");

  await tab("月");
  const cell = page.locator('.month-grid>button[data-date="2026-09-16"]');
  await cell.click();
  const total = await page.locator('.month-agenda-entry').count();
  assert.equal(await cell.locator('.month-entry').count(), Math.min(3, total));
  assert.equal(await cell.locator('.month-more').innerText(), `+${total - 3}件`);
  await page.locator('.month-grid>button[data-date="2026-09-20"]').click();
  assert.equal(await page.locator('.month-agenda-entry').filter({ hasText: "週末の小旅行" }).count(), 1);
  await page.locator('.month-grid>button[data-date="2026-09-21"]').click();
  assert.equal(await page.locator('.month-agenda-entry').filter({ hasText: "週末の小旅行" }).count(), 0);
  await page.locator('.month-grid>button[data-date="2026-09-18"]').click();
  await page.locator('.month-agenda-entry').filter({ hasText: "夜行バスで移動" }).click();
  const overnight = await get("overnight");
  assert.equal(await page.getByLabel("終了日", { exact: true }).inputValue(), "2026-09-18");
  await page.getByLabel("名前", { exact: true }).fill("夜行バスで移動・予約済み"); await save();
  assert.equal((await get("overnight")).payload.startAt, overnight.payload.startAt);
  assert.equal((await get("overnight")).payload.endAt, overnight.payload.endAt);
